var NOTE_CARE='（給小燈的提醒，不要寫出來：他可能在說自己被欺負、被取笑，或很難過。如果是他自己的事：先用一兩句溫柔地接住他的感受，再請他告訴信任的大人，例如老師、輔導老師或家人；不用帶回題目，也不要反問他「如果是你會有什麼感覺」。如果他是在說別人，或已經回到題目，就照平常的方式：先回應，最後用一個問題結束。最多三句、每句都短，'+TAIL;
var NOTE_SUM='（給小燈的提醒，不要寫出來：學生已經認真回答好幾次了，這一次不追問。第一句用「你想到」開頭回應他；再用一兩句整理他自己說過的話，不要加上他沒說過的想法；最後一句告訴他可以按「下一頁」繼續看故事，想多聊也可以。最多四句、每句都短，'+TAIL;
/* 看起來像在提問嗎：問號、嗎、什麼、為什麼、是不是… */
function asks(t){ return /[?？]\s*$|嗎\s*$|什麼\s*$|^什麼是|^你.*什麼|什麼意思|為什麼|怎麼會|怎麼辦\s*$|是不是|是誰/.test(String(t||'').trim()); }
/* 看起來像在說自己被欺負、被排擠，或很難過嗎 */
function hurt(t){ return /被[^，。！？\s]{0,6}(笑|打|欺負|霸凌|排擠|孤立)|(笑|打|欺負|霸凌|排擠|討厭|不理)我(?!們)|不(跟|和)我(玩|說話|講話|好)|我沒有?朋友|沒有?人(要|想|肯)?(跟|和|理|喜歡)我|想死|不想活|自殺|自殘|傷害自己/.test(String(t||'')); }
/* prev：學生的上一句話。剛說過自己被欺負，下一句也先用關心的提醒 */
function wrap(text,sum,prev){ return (hurt(text)||hurt(prev)?NOTE_CARE:sum?NOTE_SUM:asks(text)?NOTE_ASK:NOTE)+'\n學生寫的話：「'+text+'」'; }
/* 算不算「認真回答」：按鈕的字、太短的、提問的、說自己被欺負的、說不知道的都不算 */
function real(t){ t=String(t||'').trim();
  return !(QUICK.indexOf(t)>=0 || Array.from(t).length<4 || (t.match(/[一-鿿]/g)||[]).length<2 || asks(t) || hurt(t) || /^(我?不知道|不曉得|不清楚|還好|沒有|idk|i don.?t know)/i.test(t)); }
function sumNow(texts){ var n=texts.filter(real).length; return n>0 && n%3===0 && real(texts[texts.length-1]); }
// 把小燈的回答整理乾淨：去掉 ** 這類符號、空行，和不小心寫出來的提醒
function tidy(t){ return String(t||'').replace(/\*\*|__|`/g,'').replace(/^\s*#+\s*/gm,'').replace(/[（(]給小燈的提醒[^）)]*[）)]/g,'').replace(/\s*[（(]\d+[）)]\s*$/,'').replace(/\n\s*\n+/g,'\n').trim(); }

function cors(origin) {
  return {
    'Access-Control-Allow-Origin': origin,
    'Access-Control-Allow-Methods': 'POST, OPTIONS',
    'Access-Control-Allow-Headers': 'content-type',
    'Access-Control-Max-Age': '86400',
    'Vary': 'Origin',
  };
}
function reply(body, status, origin) {
  return new Response(JSON.stringify(body), { status, headers: { 'content-type': 'application/json; charset=utf-8', ...cors(origin) } });
}

export default {
  async fetch(request, env, ctx) {
    const origin = request.headers.get('Origin') || '';
    if (!ALLOWED_ORIGINS.includes(origin)) return new Response('Forbidden', { status: 403 });
    if (request.method === 'OPTIONS') return new Response(null, { status: 204, headers: cors(origin) });
    if (request.method !== 'POST') return reply({ error: 'method' }, 405, origin);

    let body;
    try { body = await request.json(); } catch { return reply({ error: 'bad_json' }, 400, origin); }
    const era = Number(body && body.era);
    const msgs = Array.isArray(body && body.messages) ? body.messages.slice(-MAX_TURNS) : [];
    if (!(era >= 0 && era < ERAS.length) || !msgs.length) return reply({ error: 'bad_request' }, 400, origin);

    // 整理對話：只接受 user / assistant，限制長度
    const clean = [];
    for (const m of msgs) {
      const role = m && m.role === 'user' ? 'user' : 'assistant';
      const text = String((m && m.content) || '').trim().slice(0, role === 'user' ? MAX_CHARS : 600);
      if (text) clean.push({ role, text });
    }
    if (!clean.length || clean[clean.length - 1].role !== 'user') return reply({ error: 'bad_request' }, 400, origin);
    // 學生的話加上標記；只有最新的一句前面帶一行給小燈的提醒（平常、提問、關心、整理，由 wrap 決定）
    const last = clean.length - 1;
    let prev = '';
    for (let k = last - 1; k >= 0; k--) { if (clean[k].role === 'user') { prev = clean[k].text; break; } }
    const turns = [{ role: 'assistant', content: HELLO }];
    clean.forEach((m, k) => {
      turns.push({ role: m.role, content: m.role !== 'user' ? m.text : k === last ? wrap(m.text, body.sum === true, prev) : '學生寫的話：「' + m.text + '」' });
    });
    // API 要求第一則是 user：把說明書放在 system，對話前補一句開場
    turns.unshift({ role: 'user', content: '（學生打開了討論區）' });

    const res = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        'x-api-key': env.ANTHROPIC_API_KEY,
        'anthropic-version': '2023-06-01',
      },
      body: JSON.stringify({
        model: MODEL,
        max_tokens: MAX_TOKENS,
        // cache_control：同一個年代的說明書和故事會被快取，之後只收約十分之一的價錢
        system: [{ type: 'text', text: rules(era), cache_control: { type: 'ephemeral' } }],
        messages: turns,
      }),
    });
    if (res.status === 429) return reply({ error: 'rate_limited' }, 429, origin);
    if (!res.ok) return reply({ error: 'upstream', status: res.status }, 502, origin);
    const data = await res.json();
    const text = tidy((data.content || []).filter(b => b.type === 'text').map(b => b.text).join(''));
    // 記錄到 Google 試算表（有設定 SHEET_URL 才會記錄；記錄失敗不影響小燈回答）
    if (env.SHEET_URL && text) {
      const sid = String((body && body.sid) || '').replace(/[^A-Z0-9]/g, '').slice(0, 12) || '未知';
      const row = {
        time: new Date().toLocaleString('zh-TW', { timeZone: 'Asia/Taipei', hour12: false }),
        sid,
        era: ERAS[era].when.split('　')[0] + '｜' + ERAS[era].title,
        turn: clean.filter(m => m.role === 'user').length,
        student: clean[last].text,
        reply: text,
      };
      ctx.waitUntil(fetch(env.SHEET_URL, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(row) }).catch(() => {}));
    }
    return reply({ text }, 200, origin);
  },
};
